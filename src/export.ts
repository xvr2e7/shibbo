// Write shibbo rules into the files other tools read.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { rulesMarkdown } from "./rules.js";
import { tells } from "./registry.js";

const START = "<!-- shibbo:start -->";
const END = "<!-- shibbo:end -->";

/** Insert or replace the shibbo block in a markdown file, leaving the rest alone. */
export function upsertBlock(path: string, body: string): "created" | "updated" | "unchanged" {
  const block = `${START}\n${body.trim()}\n${END}`;
  if (!existsSync(path)) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, block + "\n");
    return "created";
  }
  const cur = readFileSync(path, "utf8");
  const re = new RegExp(`${START}[\\s\\S]*?${END}`);
  const next = re.test(cur) ? cur.replace(re, block) : `${cur.trimEnd()}\n\n${block}\n`;
  if (next === cur) return "unchanged";
  writeFileSync(path, next);
  return "updated";
}

/** JS regex source → RE2 (Vale). Returns null when the pattern uses features RE2 lacks. */
export function toRe2(src: string): string | null {
  if (/\(\?<[=!]|\(\?[=!]|\\u\{|\\[1-9]/.test(src)) return null;
  return src.replace(/\\u([0-9a-fA-F]{4})/g, "\\x{$1}");
}

export function valeRules(): Record<string, string> {
  const files: Record<string, string> = {};
  for (const t of tells()) {
    if (t.detect.method !== "regex" || !t.detect.pattern || !["prose", "chat"].includes(t.domain) || t.severity === 0) continue;
    if ((t.detect.flags ?? "i").includes("m")) continue; // line anchors behave differently in Vale scopes
    const re = toRe2(t.detect.pattern);
    if (!re) continue;
    const name = t.id.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("");
    const level = t.severity >= 3 ? "error" : t.severity === 2 ? "warning" : "suggestion";
    const msg = (t.fix ?? t.what).replace(/'/g, "''");
    files[`${name}.yml`] = [
      `# Generated by shibbo from data/tells.yaml (${t.id}). Do not edit by hand.`,
      "extends: existence",
      `message: '${t.name.replace(/'/g, "''")}: %s. ${msg}'`,
      `level: ${level}`,
      `ignorecase: ${!(t.detect.flags ?? "i").includes("i") ? "false" : "true"}`,
      "nonword: true",
      "tokens:",
      `  - '${re.replace(/'/g, "''")}'`,
      "",
    ].join("\n");
  }
  return files;
}

export function runExport(target: string | undefined, opts: { model: string | null; out: string }) {
  const rules = rulesMarkdown({ model: opts.model });
  switch (target) {
    case "claude": {
      const p = join(opts.out, "CLAUDE.md");
      console.log(`${upsertBlock(p, rules)} ${p}`);
      return;
    }
    case "agents": {
      const p = join(opts.out, "AGENTS.md");
      console.log(`${upsertBlock(p, rules)} ${p}`);
      return;
    }
    case "cursor": {
      const p = join(opts.out, ".cursor", "rules", "shibbo.mdc");
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, `---\ndescription: Avoid writing patterns that read as machine-made (shibbo)\nalwaysApply: true\n---\n\n${rules}\n`);
      console.log(`wrote ${p}`);
      return;
    }
    case "vale": {
      const dir = join(opts.out, "styles", "Shibbo");
      mkdirSync(dir, { recursive: true });
      const files = valeRules();
      for (const [name, body] of Object.entries(files)) writeFileSync(join(dir, name), body);
      console.log(`wrote ${Object.keys(files).length} Vale rules to ${dir}. Add "BasedOnStyles = Shibbo" to .vale.ini.`);
      return;
    }
    default:
      console.error("export target must be one of: claude, agents, cursor, vale");
      process.exitCode = 2;
  }
}
